/** Polish plural forms: 1 plik, 2 pliki, 5 plików (and 12 plików, 22 pliki). */
const pl = (n: number, one: string, few: string, many: string) => {
  if (n === 1) return one
  const d = n % 10
  const h = n % 100
  return d >= 2 && d <= 4 && (h < 12 || h > 14) ? few : many
}
const files = (n: number) => `${n} ${pl(n, 'plik', 'pliki', 'plików')}`

