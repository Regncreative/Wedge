import { useEffect, useState } from 'react'
import { motion } from 'framer-motion'
import { Smartphone, X } from 'lucide-react'
import type { PhoneSession } from '@shared/types'
import { useStashStore } from '@/stores/stash-store'
import { useT } from '@/lib/i18n'

/** QR code for sending files from a phone on the same Wi-Fi. */
export function PhoneSheet() {
  const t = useT()
  const open = useStashStore((s) => s.phoneOpen)
  const setOpen = useStashStore((s) => s.setPhoneOpen)
  const [session, setSession] = useState<PhoneSession | null>(null)
  const [error, setError] = useState(false)
  const [now, setNow] = useState(Date.now())

  useEffect(() => {
    if (!open) return
    setError(false)
    void window.stash
      .phoneStart()
      .then(setSession)
      .catch(() => setError(true))
    const tick = window.setInterval(() => setNow(Date.now()), 30_000)
    const onKey = (e: KeyboardEvent) => {
      if (e.key === 'Escape') {
        e.stopPropagation()
        setOpen(false)
      }
    }
    window.addEventListener('keydown', onKey, true)
    return () => {
      window.clearInterval(tick)
      window.removeEventListener('keydown', onKey, true)
      setSession(null)
      void window.stash.phoneStop()
    }
  }, [open, setOpen])

  if (!open) return null
  const minutes = session ? Math.max(1, Math.round((session.expiresAt - now) / 60_000)) : 0

  return (
    <div
      className="absolute inset-0 z-[83] flex items-center justify-center bg-black/45 px-6"
      onMouseDown={(e) => e.target === e.currentTarget && setOpen(false)}
    >
      <motion.div
        role="dialog"
        aria-modal="true"
        aria-labelledby="phone-title"
        initial={{ opacity: 0, y: 10 }}
        animate={{ opacity: 1, y: 0 }}
        className="w-full max-w-[340px] rounded-[18px] border border-[var(--border)] bg-[var(--card)] p-5 text-center shadow-[var(--hover-shadow)]"
      >
        <div className="flex items-center justify-between">
          <h2 id="phone-title" className="flex items-center gap-2 text-[15px] font-semibold text-[var(--foreground)]">
            <Smartphone size={17} strokeWidth={1.75} />
            {t.phoneTitle}
          </h2>
          <button type="button" className="icon-btn" aria-label={t.close} onClick={() => setOpen(false)}>
            <X size={16} strokeWidth={1.75} />
          </button>
        </div>
        {error ? (
          <p className="mt-6 text-[13px] text-[var(--destructive)]">{t.phoneError}</p>
        ) : !session ? (
          <div className="mx-auto my-12 h-5 w-5 animate-pulse rounded-full bg-[var(--accent)] opacity-70" />
        ) : (
          <>
            <div
              className="mx-auto mt-4 w-[210px] overflow-hidden rounded-[12px] bg-white p-1 [&>svg]:h-auto [&>svg]:w-full"
              aria-label={session.url}
              role="img"
              // Generated by the backend's QR encoder (no user content).
              dangerouslySetInnerHTML={{ __html: session.qrSvg }}
            />
            <p className="mt-3 select-all break-all text-[11px] text-[var(--muted-foreground)]">
              {session.url}
            </p>
            <p className="mt-3 text-[12px] leading-snug text-[var(--foreground)]">{t.phoneHint}</p>
            <p className="mt-2 text-[11px] leading-snug text-[var(--muted-foreground)]">
              {t.phoneFirewall} · {t.phoneExpires(minutes)}
            </p>
          </>
        )}
      </motion.div>
    </div>
  )
}
